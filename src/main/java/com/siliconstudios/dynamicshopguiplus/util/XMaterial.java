    @Nonnull
    public static XMaterial matchXMaterial(@Nonnull ItemStack item) {
        Optional<XMaterial> result;
        Objects.requireNonNull(item, "Cannot match null ItemStack");
        String material = item.getType().name();
        int data = Data.ISFLAT || item.getType().getMaxDurability() > 0 ? -1 : (int)item.getDurability();
        if (!Data.ISFLAT && material.equals("POTION")) {
            data = -1;
        }
        if ((result = XMaterial.matchDefinedXMaterial(material, (byte)data)).isPresent()) {
            return result.get();
        }
        SendMessage.logDebugMessage("Matching item with unsupported material: " + material + " (" + data + "), skipping...");
        return AIR;
    }

    @Nonnull
    protected static Optional<XMaterial> matchDefinedXMaterial(@Nonnull String name, byte data) {
        Optional<XMaterial> xMaterial;
        Boolean duplicated = null;
        boolean isAMap = name.equalsIgnoreCase("MAP");
        if ((Data.ISFLAT || !isAMap && data <= 0 && !(duplicated = Boolean.valueOf(XMaterial.isDuplicated(name))).booleanValue()) && (xMaterial = XMaterial.getIfPresent(name)).isPresent()) {
            return xMaterial;
        }
        XMaterial oldXMaterial = XMaterial.requestOldXMaterial(name, data);
        if (oldXMaterial == null) {
            return data >= 0 && isAMap ? Optional.of(FILLED_MAP) : Optional.empty();
        }
        if (!Data.ISFLAT && (duplicated == null ? XMaterial.isDuplicated(name) : duplicated != false)) {
            return XMaterial.getIfPresent(name);
        }
        return Optional.of(oldXMaterial);
    }

