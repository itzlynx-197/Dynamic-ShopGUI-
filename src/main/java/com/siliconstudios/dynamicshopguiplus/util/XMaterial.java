    @Nullable
    private static XMaterial requestOldXMaterial(@Nonnull String name, byte data) {
        String holder = name + data;
        XMaterial cache = (XMaterial)((Object)NAME_CACHE.getIfPresent((Object)holder));
        if (cache != null) {
            return cache;
        }
        for (XMaterial material : VALUES) {
            if (data != -1 && data != material.data || !material.anyMatchLegacy(name)) continue;
            NAME_CACHE.put(holder, material);
            return material;
        }
        return null;
    }

    @Nonnull
    public static Optional<XMaterial> matchXMaterial(@Nonnull String name) {
        Validate.notEmpty((String)name, (String)"Cannot match a material with null or empty material name");
        Optional<XMaterial> oldMatch = XMaterial.matchXMaterialWithData(name);
        return oldMatch.isPresent() ? oldMatch : XMaterial.matchDefinedXMaterial(XMaterial.format(name), (byte)-1);
    }

    @Nonnull
    private static Optional<XMaterial> matchXMaterialWithData(@Nonnull String name) {
        int index = name.indexOf(58);
        if (index != -1) {
            String mat = XMaterial.format(name.substring(0, index));
            try {
                byte data = (byte)Integer.parseInt(StringUtils.deleteWhitespace((String)name.substring(index + 1)));
                return data >= 0 && data < 120 ? XMaterial.matchDefinedXMaterial(mat, data) : XMaterial.matchDefinedXMaterial(mat, (byte)-1);
            }
            catch (NumberFormatException ignored) {
                return XMaterial.matchDefinedXMaterial(mat, (byte)-1);
            }
        }
        return Optional.empty();
    }

    public static XMaterial matchXMaterial(@Nonnull Block block) {
        Step step;
        if (Data.ISFLAT) {
            return XMaterial.matchXMaterial(block.getType());
        }
        String type = block.getType().name();
        byte dataValue = -1;
        MaterialData blockData = block.getState().getData();
        if (blockData instanceof Step) {
            step = (Step)blockData;
            if (step.isInverted() || type.equals("DOUBLE_STEP")) {
                dataValue = (byte)Integer.parseInt(String.valueOf(step.getData() & 7));
            }
        } else if (blockData instanceof WoodenStep) {
            WoodenStep wstep = (WoodenStep)blockData;
            if (wstep.isInverted() || type.equals("WOOD_DOUBLE_STEP")) {
                dataValue = (byte)Integer.parseInt(String.valueOf(wstep.getData() & 7));
            }
        } else if (!type.contains("CHEST")) {
            dataValue = block.getData();
        }
        byte finalDataValue = dataValue;
        return XMaterial.matchDefinedXMaterial(type, dataValue).orElseThrow(() -> new IllegalArgumentException("Unsupported material for block " + finalDataValue + ": " + block.getType().name()));
    }

