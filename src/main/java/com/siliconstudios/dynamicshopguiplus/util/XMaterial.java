    public static double getBlockY(Block block) {
        double extra = 0.5;
        if (block.getType() != Material.CHEST && block.getType() != Material.ENDER_CHEST) {
            WoodenStep step;
            if (ServerInfo.getVersion().newerOrEqualAs(ServerInfo.Version.v1_13_R1) && block.getState().getBlockData() instanceof Slab) {
                Slab slab = (Slab)block.getState().getBlockData();
                if (slab.getType() == Slab.Type.BOTTOM) {
                    extra -= 0.5;
                }
            } else if (block.getState().getData() instanceof Step) {
                Step step2 = (Step)block.getState().getData();
                if (!step2.isInverted()) {
                    extra -= 0.5;
                }
            } else if (block.getState().getData() instanceof WoodenStep && !(step = (WoodenStep)block.getState().getData()).isInverted()) {
                extra -= 0.5;
            }
        }
        return (double)block.getLocation().getBlockY() + extra;
    }

    @Nonnull
    protected static String format(@Nonnull String name) {
        int len = name.length();
        char[] chs = new char[len];
        int count = 0;
        boolean appendUnderline = false;
        for (int i = 0; i < len; ++i) {
            char ch = name.charAt(i);
            if (!(appendUnderline || count == 0 || ch != '-' && ch != ' ' && ch != '_' || chs[count] == '_')) {
                appendUnderline = true;
                continue;
            }
            boolean number = false;
            if (!(ch >= 'A' && ch <= 'Z' || ch >= 'a' && ch <= 'z') && !(number = ch >= '0' && ch <= '9')) continue;
            if (appendUnderline) {
                chs[count++] = 95;
                appendUnderline = false;
            }
            chs[count++] = number ? ch : (char)(ch & 0x5F);
        }
        return new String(chs, 0, count);
    }

